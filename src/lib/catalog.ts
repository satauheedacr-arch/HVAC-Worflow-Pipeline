// Helper to convert catalog rows into structured Material array with default min stock
export function buildInitialMaterials(): Material[] {
  return CATALOG_ROWS.map((row) => {
    const [code, category, subCategory, name, spec, purchaseUnit, issueUnit, defaultVendorId, notes, rare, customSize] = row;
    // Set realistic minStock for common items
    let minStock = 0;
    if (code === "COP-S-02") minStock = 20; // 1/4" High density pipe
    if (code === "COP-S-03") minStock = 15; // 3/8" pipe
    if (code === "FIT-ELB-02") minStock = 30; // 3/4" elbow
    if (code === "INS-TUB-03") minStock = 50; // 1/4" x 13mm
    if (code === "GAS-02") minStock = 5; // R-32 gas
    if (code === "CBL-03") minStock = 100; // 1.5 Sqmm cable
    if (code === "FST-01") minStock = 40; // 8mm rod

    return {
      id: `m-${code.toLowerCase().replace(/[^a-z0-9]/g, "-")}`,
      code,
      category,
      subCategory,
      name,
      spec,
      purchaseUnit,
      issueUnit,
      defaultVendorId,
      notes,
      rare: Boolean(rare),
      customSize: Boolean(customSize),
      minStock,
      active: true,
      inStoreAdjustment: 0,
    };
  });
}
